document.addEventListener("keydown", (event) => {
  if (gallery.open) {
    if (event.key === "ArrowLeft") changeSlide(-1, { animate: false });
    if (event.key === "ArrowRight") changeSlide(1, { animate: false });
    return;
  }

  const menuOpen = menuToggle.getAttribute("aria-expanded") === "true";
  if (!menuOpen) return;

  if (event.key === "Escape") {
    event.preventDefault();
    setMenu(false, { animate: false });
    return;
  }

  if (event.key === "Tab") {
    const focusable = [menuToggle, ...navigation.querySelectorAll("a")];
    const first = focusable[0];
    const last = focusable.at(-1);
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

if ("IntersectionObserver" in window) {
  document.documentElement.classList.add("reveal-enabled");
  const revealElements = [...document.querySelectorAll("[data-reveal]")];
  revealElements.forEach((element) => {
    const siblings = [...element.parentElement.querySelectorAll(":scope > [data-reveal]")];
    const order = Math.min(Math.max(siblings.indexOf(element), 0), 4);
    element.style.setProperty("--reveal-delay", `${order * 45}ms`);
  });

  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      });
    },
    { rootMargin: "0px 0px -7%", threshold: 0.08 },
  );

  revealElements.forEach((element) => revealObserver.observe(element));

  if (hero && floatingContact) {
    floatingContact.classList.add("is-managed");
    const heroObserver = new IntersectionObserver(
      ([entry]) => floatingContact.classList.toggle("is-muted", entry.isIntersecting),
      { threshold: 0.16 },
    );
    heroObserver.observe(hero);
  }
}
