const bodyLocks = new Set();

function lockBody(reason) {
  if (bodyLocks.has(reason)) return;
  if (bodyLocks.size === 0) {
    lockedScrollY = window.scrollY;
    body.style.position = "fixed";
    body.style.top = `-${lockedScrollY}px`;
    body.style.width = "100%";
  }
  bodyLocks.add(reason);
}

function unlockBody(reason) {
  bodyLocks.delete(reason);
  if (bodyLocks.size !== 0) return;
  body.style.position = "";
  body.style.top = "";
  body.style.width = "";
  window.scrollTo(0, lockedScrollY);
}

function setPageInert(inert) {
  [pageMain, footer, floatingContact, brand].forEach((element) => {
    if (element) element.inert = inert;
  });
}

function setMenu(open, { animate = true, returnFocus = true } = {}) {
  const wasOpen = menuToggle.getAttribute("aria-expanded") === "true";
  if (open === wasOpen) return;

  navigation.classList.toggle("is-instant", !animate);
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", open ? "Закрыть меню" : "Открыть меню");
  navigation.classList.toggle("is-open", open);
  body.classList.toggle("is-menu-open", open);
  setPageInert(open);

  if (open) {
    lockBody("menu");
    window.requestAnimationFrame(() => navigation.querySelector("a")?.focus());
  } else {
    unlockBody("menu");
    if (returnFocus) menuToggle.focus({ preventScroll: true });
  }

  window.requestAnimationFrame(() => {
    window.requestAnimationFrame(() => navigation.classList.remove("is-instant"));
  });
}

menuToggle.addEventListener("click", (event) => {
  setMenu(menuToggle.getAttribute("aria-expanded") !== "true", {
    animate: event.detail !== 0,
  });
});

navigation.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", (event) =>
    setMenu(false, { animate: event.detail !== 0, returnFocus: false }),
  );
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 960) setMenu(false, { animate: false, returnFocus: false });
});

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    await navigator.clipboard.writeText(text);
    return;
  }

  const textArea = document.createElement("textarea");
  textArea.value = text;
  textArea.setAttribute("readonly", "");
  textArea.style.position = "fixed";
  textArea.style.opacity = "0";
  document.body.append(textArea);
  textArea.focus({ preventScroll: true });
  textArea.select();
  textArea.setSelectionRange(0, text.length);

  let copied = false;
  try {
    copied = document.execCommand("copy");
  } finally {
    textArea.remove();
  }
  if (!copied) throw new Error("Copy command failed");
}

if (copyEmailButton) {
  const label = copyEmailButton.querySelector(".copy-email-label");
  let resetTimer;

  async function updateCopyLabel(text) {
    copyLabelToken += 1;
    const token = copyLabelToken;
    copyLabelAnimation?.cancel();

    if (!label.animate) {
      label.textContent = text;
      return;
    }

    copyLabelAnimation = label.animate([{ opacity: 1 }, { opacity: 0 }], {
      duration: 110,
      easing: "cubic-bezier(0.77, 0, 0.175, 1)",
    });
    try {
      await copyLabelAnimation.finished;
    } catch {
      return;
    }
    if (token !== copyLabelToken) return;

    label.textContent = text;
    copyLabelAnimation = label.animate([{ opacity: 0 }, { opacity: 1 }], {
      duration: 150,
      easing: "cubic-bezier(0.23, 1, 0.32, 1)",
    });
  }

  copyEmailButton.addEventListener("click", async () => {
    clearTimeout(resetTimer);

    try {
      await copyText(copyEmailButton.dataset.email);
      void updateCopyLabel("E-mail скопирован");
      copyEmailButton.classList.add("is-copied");
    } catch {
      void updateCopyLabel("Не удалось, выделите адрес");
      copyEmailButton.classList.remove("is-copied");
    }

    resetTimer = window.setTimeout(() => {
      void updateCopyLabel("Скопировать e-mail");
      copyEmailButton.classList.remove("is-copied");
    }, 2400);
  });
}

function normalizedImage(project, index) {
  const image = project.images[index];
  if (Array.isArray(image)) {
    return {
      src: image[0],
      alt: image[1],
      title: project.title,
      meta: project.meta,
      description: project.description,
      points: project.points,
    };
  }
  return { ...image, points: image.points || project.points };
}

function renderPoints(points) {
  galleryPoints.innerHTML = "";
  galleryPoints.hidden = points.length === 0;
  points.forEach(([heading, text]) => {
    const item = document.createElement("li");
    const strong = document.createElement("strong");
    strong.textContent = heading;
    item.append(strong, document.createTextNode(text));
    galleryPoints.append(item);
  });
}

function renderMeta(meta) {
  const parts = Array.isArray(meta) ? meta : [meta];
  galleryMeta.replaceChildren(
    ...parts.map((part) => {
      const item = document.createElement("span");
      item.textContent = part;
      return item;
    }),
  );
}

function renderGallery({ updateImage = true } = {}) {
  const project = projects[activeProject];
  const image = normalizedImage(project, activeIndex);

  galleryNumber.textContent = project.number;
  galleryKicker.textContent = project.kicker;
  if (updateImage) {
    galleryImage.src = image.src;
    galleryImage.alt = image.alt;
  }
  galleryTitle.textContent = image.title;
  renderMeta(image.meta);
  galleryDescription.textContent = image.description;
  galleryCurrent.textContent = String(activeIndex + 1);
  galleryTotal.textContent = String(project.images.length);
  renderPoints(image.points || []);

  galleryThumbnails.querySelectorAll("button").forEach((button, index) => {
    const isActive = index === activeIndex;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-current", isActive ? "true" : "false");
  });
}

function cancelSlideAnimations() {
  slideAnimations.forEach((animation) => animation.cancel());
  slideAnimations = [];
  slideOverlay?.remove();
  slideOverlay = null;
  galleryImage.style.removeProperty("opacity");
  galleryImage.style.removeProperty("transform");
}

function showSlide(index, { direction = 1, animate = true } = {}) {
  if (index === activeIndex) return;
  cancelSlideAnimations();

  const outgoing = galleryImage.cloneNode();
  outgoing.removeAttribute("id");
  outgoing.className = "gallery-slide-outgoing";
  outgoing.alt = "";
  outgoing.setAttribute("aria-hidden", "true");
  galleryStage.insertBefore(outgoing, galleryPrev);
  slideOverlay = outgoing;

  activeIndex = index;
  const image = normalizedImage(projects[activeProject], activeIndex);
  galleryImage.src = image.src;
  galleryImage.alt = image.alt;
  renderGallery({ updateImage: false });

  if (!animate || !galleryImage.animate) {
    cancelSlideAnimations();
    return;
  }

  const reduced = reduceMotion.matches;
  const distance = reduced ? 0 : 8;
  const outgoingAnimation = outgoing.animate(
    [
      { opacity: 1, transform: "translateX(0)" },
      { opacity: 0, transform: `translateX(${-direction * distance}px)` },
    ],
    {
      duration: reduced ? 160 : 120,
      easing: "cubic-bezier(0.77, 0, 0.175, 1)",
      fill: "forwards",
    },
  );
  const incomingAnimation = galleryImage.animate(
    [
      { opacity: 0, transform: `translateX(${direction * distance}px)` },
      { opacity: 1, transform: "translateX(0)" },
    ],
    {
      duration: reduced ? 160 : 170,
      easing: "cubic-bezier(0.23, 1, 0.32, 1)",
      fill: "both",
    },
  );
  slideAnimations = [outgoingAnimation, incomingAnimation];
  Promise.allSettled(slideAnimations.map((animation) => animation.finished)).then(() => {
    if (slideOverlay !== outgoing) return;
    cancelSlideAnimations();
  });
}

function buildThumbnails(project) {
  galleryThumbnails.innerHTML = "";
  project.images.forEach((_, index) => {
    const image = normalizedImage(project, index);
    const button = document.createElement("button");
    const thumbnail = document.createElement("img");

    button.type = "button";
    button.setAttribute("aria-label", `Открыть изображение ${index + 1}`);
    thumbnail.src = image.src;
    thumbnail.alt = "";
    thumbnail.loading = "lazy";
    button.append(thumbnail);
    button.addEventListener("click", (event) => {
      showSlide(index, {
        direction: index > activeIndex ? 1 : -1,
        animate: event.detail !== 0,
      });
    });
    galleryThumbnails.append(button);
  });
}

function cancelModalAnimations() {
  modalAnimations.forEach((animation) => animation.cancel());
  modalAnimations = [];
}

function openGallery(projectKey, { opener = null, animate = true } = {}) {
  setMenu(false, { animate: false, returnFocus: false });
  galleryOpener = opener;
  activeProject = projectKey;
  activeIndex = 0;
  buildThumbnails(projects[projectKey]);
  renderGallery();
  gallery.showModal();
  body.classList.add("is-gallery-open");
  lockBody("gallery");
  galleryClose.focus({ preventScroll: true });

  if (!animate || !gallery.animate) return;
  cancelModalAnimations();
  const reduced = reduceMotion.matches;
  modalAnimations = [
    gallery.animate([{ opacity: 0 }, { opacity: 1 }], {
      duration: reduced ? 160 : 260,
      easing: "cubic-bezier(0.23, 1, 0.32, 1)",
    }),
    galleryShell.animate(
      [
        {
          opacity: reduced ? 0 : 1,
          transform: reduced ? "none" : "translateY(6px) scale(0.985)",
        },
        { opacity: 1, transform: "translateY(0) scale(1)" },
      ],
      {
        duration: reduced ? 160 : 260,
        easing: "cubic-bezier(0.23, 1, 0.32, 1)",
      },
    ),
  ];
}

async function closeGallery({ animate = true } = {}) {
  if (!gallery.open) return;
  modalAnimationToken += 1;
  const token = modalAnimationToken;
  cancelModalAnimations();
  cancelSlideAnimations();

  if (animate && gallery.animate) {
    const reduced = reduceMotion.matches;
    modalAnimations = [
      gallery.animate([{ opacity: 1 }, { opacity: 0 }], {
        duration: reduced ? 160 : 200,
        easing: "cubic-bezier(0.77, 0, 0.175, 1)",
        fill: "forwards",
      }),
      galleryShell.animate(
        [
          { opacity: 1, transform: "translateY(0) scale(1)" },
          {
            opacity: reduced ? 0 : 1,
            transform: reduced ? "none" : "translateY(6px) scale(0.985)",
          },
        ],
        {
          duration: reduced ? 160 : 200,
          easing: "cubic-bezier(0.77, 0, 0.175, 1)",
          fill: "forwards",
        },
      ),
    ];
    await Promise.allSettled(modalAnimations.map((animation) => animation.finished));
  }

  if (token === modalAnimationToken && gallery.open) gallery.close();
}

function changeSlide(delta, { animate = true } = {}) {
  const count = projects[activeProject].images.length;
  const nextIndex = (activeIndex + delta + count) % count;
  showSlide(nextIndex, { direction: Math.sign(delta), animate });
}

